"""Dot-matrix glyph preview + picker-preview vector generator.

Parses the glyph table out of DotText.kt (single source of truth).

  python tools/preview_dots.py png out.png          # contact sheet of the glyph set (needs Pillow)
  python tools/preview_dots.py vectors              # (re)writes app/src/main/res/drawable/pv_*.xml
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "app/src/main/java/io/github/oceansde012/dotline/DotText.kt").read_text(encoding="utf-8")
BLOCK = re.search(r'SRC = """\n(.*?)"""', SRC, re.S).group(1)
GLYPHS = {}
for line in BLOCK.splitlines():
    if len(line) >= 4:
        GLYPHS[line[0]] = line[2:].split("/")


def layout(text):
    """list of (col, row) lit cells and the total column count"""
    x, first, lit = 0, True, []
    for ch in text:
        g = GLYPHS.get(ch.upper(), GLYPHS.get(ch))
        w = 3 if ch == " " else (len(g[0]) if g else 0)
        if w == 0:
            continue
        if not first:
            x += 1
        first = False
        if g:
            for r, row in enumerate(g):
                for c, v in enumerate(row):
                    if v == "#":
                        lit.append((x + c, r))
        x += w
    return lit, max(x, 1)


def png(path):
    from PIL import Image, ImageDraw
    lines = ["0123456789", "12:59 10° 81%", "ABCDEFGHIJKLM", "NOPQRSTUVWXYZ", "-+.,/!?()'_=· ~ L80 R75"]
    pitch = 12
    img = Image.new("RGB", (30 * 6 * pitch, len(lines) * 9 * pitch + pitch), (16, 16, 18))
    d = ImageDraw.Draw(img)
    for li, t in enumerate(lines):
        lit, cols = layout(t)
        y0 = li * 9 * pitch + pitch
        for c in range(cols):
            for r in range(7):
                d.ellipse([c * pitch + pitch * .19, y0 + r * pitch + pitch * .19, c * pitch + pitch * .81, y0 + r * pitch + pitch * .81], fill=(34, 34, 36))
        for c, r in lit:
            d.ellipse([c * pitch + pitch * .19, y0 + r * pitch + pitch * .19, c * pitch + pitch * .81, y0 + r * pitch + pitch * .81], fill=(242, 242, 242))
    img.save(path)


def vector(name, text, pitch_dp):
    lit, cols = layout(text)
    r = 3.1
    def circ(c, rr):
        cx, cy = c * 10 + 5, rr * 10 + 5
        return f"M{cx - r:.1f},{cy:.1f}a{r},{r} 0 1,0 {2 * r:.1f},0a{r},{r} 0 1,0 {-2 * r:.1f},0z"
    off = "".join(circ(c, rr) for c in range(cols) for rr in range(7) if (c, rr) not in set(lit))
    on = "".join(circ(c, rr) for c, rr in lit)
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/preview_dots.py: "{text}" for the widget picker preview -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{cols * pitch_dp:.1f}dp"
    android:height="{7 * pitch_dp:.1f}dp"
    android:viewportWidth="{cols * 10}"
    android:viewportHeight="70">
    <path android:fillColor="#992C2C2F" android:pathData="{off}" />
    <path android:fillColor="#F2F2F2" android:pathData="{on}" />
</vector>
'''
    (ROOT / f"app/src/main/res/drawable/pv_{name}.xml").write_text(xml, encoding="utf-8")


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "vectors"
    if mode == "png":
        png(sys.argv[2])
    else:
        vector("clock_h", "10", 9)
        vector("clock_m", "09", 9)
        vector("head_day", "23", 5)
        vector("wx_temp", "10°", 6.5)
        vector("power_num", "81", 4.4)
        vector("buds_read", "L80 R75", 1.9)
